// --- Power Control Gates (Waveshare ESP32-S3-ePaper-1.54) ---
#define PIN_MAIN_PWR        17      // Main peripheral power rail (LDO enable, active HIGH)
#define PIN_EPD_PWR         6       // Display power gate (P-MOSFET, active LOW)
#define PIN_AUDIO_PWR       42      // Audio circuit power gate (P-MOSFET, active LOW)
#define PIN_AUDIO_PA        46      // NS4150B Power Amplifier Enable (Active HIGH)
#define PIN_VBAT_ADC        4       // Battery ADC sensing (ADC1_CHANNEL_3)
#define PIN_VBAT_PWR        17      // Backward compatibility alias

#define MAIN_PWR_ON         HIGH
#define MAIN_PWR_OFF        LOW
#define EPD_PWR_ON          LOW
#define EPD_PWR_OFF         HIGH
#define AUDIO_PWR_ON        LOW
#define AUDIO_PWR_OFF       HIGH
#define AUDIO_PA_ON         HIGH
#define AUDIO_PA_OFF        LOW

// --- E-Paper Display (SPI 200x200 1.54") ---
#define PIN_EPD_BUSY        8
#define PIN_EPD_RST         9
#define PIN_EPD_DC          10
#define PIN_EPD_CS          11
#define PIN_EPD_SCK         12
#define PIN_EPD_MOSI        13

#define EPD_WIDTH           200
#define EPD_HEIGHT          200
#define EPD_BUFFER_SIZE     (EPD_WIDTH * EPD_HEIGHT / 8) // 5000 bytes

// --- I2C Bus (Shared: ES8311 Audio Codec, SHTC3 Sensor, PCF85063 RTC) ---
#define PIN_I2C_SDA         47
#define PIN_I2C_SCL         48
#define I2C_FREQ_HZ         400000

#define ES8311_I2C_ADDR     0x18
#define RTC_PCF85063_ADDR   0x51
#define SHTC3_I2C_ADDR      0x70

// --- I2S Audio Bus (ES8311 Codec) ---
#define PIN_I2S_MCLK        14      // Master Clock generated by ESP32-S3
#define PIN_I2S_BCLK        15      // Bit Clock
#define PIN_I2S_WS          38      // Word Select (LRCK)
#define PIN_I2S_DOUT        45      // Data OUT from ESP32 -> ES8311 DSDIN (Speaker)
#define PIN_I2S_DIN         16      // Data IN to ESP32 <- ES8311 ASDOUT (Mic)

#define AUDIO_SAMPLE_RATE   16000   // 16 kHz sample rate
#define AUDIO_BITS_PER_SMP  16      // 16-bit PCM
#define AUDIO_CHANNELS      1       // Mono
#define AUDIO_MAX_REC_SEC   5       // Max voice recording duration (5 seconds)

// --- Buttons & Peripherals ---
#define PIN_BOOT_BUTTON     0       // BOOT button on GPIO 0 (Active LOW, internal pull-up)
