// Mutex recursivo global para proteger el bus I2C compartido (ES8311, SHTC3, PCF85063)
bool copitoI2cLock(uint32_t timeoutMs = 500);
void copitoI2cUnlock();
struct CopitoI2cGuard {
    bool locked;
    explicit CopitoI2cGuard(uint32_t ms = 500) : locked(copitoI2cLock(ms)) {}
    ~CopitoI2cGuard() { if (locked) copitoI2cUnlock(); }
};

